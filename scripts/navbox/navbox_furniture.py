"""Generate the tile-backed furniture navbox."""

from __future__ import annotations

import os
import re
from pathlib import Path

from scripts.core.cache import load_cache
from scripts.core.constants import DATA_DIR
from scripts.core.page_manager import get_pages, init as init_pages
from scripts.items.groups.furniture_groups import FurnitureGroups
from scripts.navbox.navbox import Navbox
from scripts.utils import echo


NAMED_FURNITURE_CACHE_FILE = "named_furniture.json"
OUTPUT_FILENAME = "furniture.json"
TABLE_NAME = "Furniture"


def load_named_furniture() -> dict:
    """Load named furniture generated by the tile parsing pipeline."""
    cache_path = os.path.join(DATA_DIR, NAMED_FURNITURE_CACHE_FILE)
    named_furniture = load_cache(cache_path, "Named furniture")
    if not named_furniture:
        raise FileNotFoundError(
            f"Furniture data was not found at '{cache_path}'. "
            "Run the tile parser before generating the furniture navbox."
        )
    return named_furniture


def _fallback_page_name(group_name: str) -> str:
    """Convert an internal furniture variant suffix into a page title."""
    match = re.match(r"^(?P<base>.*)_(?P<number>\d{1,3}|1000)$", group_name)
    if not match:
        return group_name
    return f"{match.group('base')} (variant {match.group('number')})"


def resolve_furniture_page(group_name: str, variants: dict) -> tuple[str, bool]:
    """Return a furniture page from its sprite IDs, with a name fallback."""
    for sprite_id in variants:
        pages = get_pages(sprite_id, id_type="sprite_id")
        if pages:
            return pages[0], True
    return _fallback_page_name(group_name), False


def build_furniture_navbox(
    named_furniture: dict | None = None,
    section_order: list[str] | None = None,
) -> Navbox:
    """Build a navbox containing grouped furniture tile pages."""
    init_pages()
    named_furniture = named_furniture or load_named_furniture()
    navbox = Navbox(TABLE_NAME)

    for group_name, variants in named_furniture.items():
        if not isinstance(variants, dict) or not variants:
            continue

        representative = next(iter(variants.values()))
        if not FurnitureGroups.is_included(representative):
            continue

        group_id = FurnitureGroups.find_type(representative)
        page_name, has_page = resolve_furniture_page(group_name, variants)
        if not has_page:
            echo.warning(
                f"Furniture group does not have a mapped page: {group_name}"
            )

        navbox.add_item(FurnitureGroups.get_display_name(group_id), page_name)

    navbox.sort(sections=False, items=True)
    navbox.sort_sections_by_order(
        section_order or FurnitureGroups.get_section_order()
    )
    return navbox


def generate_furniture_navbox(
    output_dir: str | Path | None = None,
    named_furniture: dict | None = None,
    section_order: list[str] | None = None,
) -> Path:
    """Generate and save the furniture navbox JSON file."""
    navbox = build_furniture_navbox(
        named_furniture=named_furniture,
        section_order=section_order,
    )
    path = navbox.save(OUTPUT_FILENAME, output_dir=output_dir)
    echo.success(f"Saved furniture navbox: {path}")
    return path


def main() -> None:
    generate_furniture_navbox()


if __name__ == "__main__":
    main()
